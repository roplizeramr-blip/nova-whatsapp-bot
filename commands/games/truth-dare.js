function pickItem(arr, except) {
  let item = arr[Math.floor(Math.random() * arr.length)];
  if (arr.length > 1 && item === except) {
    item = arr[(arr.indexOf(item) + 1) % arr.length];
  }
  return item;
}

export default {
  name: 'td',
  aliases: ['حقيقة', 'جرأة', 'حقيقة_وجرأة', 'صراحة', 'لف_الزجاجة', 'ازازة', 'spin'],
  description: 'لعبة حقيقة وجرأة ولف الزجاجة الجماعية — اختار حقيقة، جرأة، أو لِف الإزازة في الجروب',
  usage: '.td  أو  .td truth  أو  .td dare  أو  .td spin',
  async execute(sock, m, args) {
    const rawArg = (args[0] ?? '').trim().toLowerCase();
    const games = db.get('td', {});
    const last = games[m.jid];

    // 🍾 وضع لف الزجاجة (Spin the Bottle) في الجروبات!
    if (['spin', 'ازازة', 'زجاجة', 'لفة', 'لف'].includes(rawArg)) {
      if (!m.isGroup) {
        return m.reply('🍾 ميزة لف الزجاجة بتتلعب في الجروبات وسط الشلة واللمة الحلوة! جربها في جروب.');
      }

      try {
        const metadata = await sock.groupMetadata(m.jid);
        const participants = metadata.participants.map((p) => p.id);
        if (participants.length < 2) {
          return m.reply('لازم يكون فيه أعضاء كفاية في الجروب عشان نلف الإزازة! 🍾');
        }

        // اختيار شخصين عشوائيين: السائل والضحية
        const p1 = participants[Math.floor(Math.random() * participants.length)];
        let p2 = participants[Math.floor(Math.random() * participants.length)];
        if (participants.length > 1 && p1 === p2) {
          p2 = participants.find((p) => p !== p1) || p2;
        }

        const tag1 = '@' + p1.split('@')[0];
        const tag2 = '@' + p2.split('@')[0];

        const spinText = [
          `🍾 *دارت الإزازة ولفت في الجروب... ووقفت!* 🎯`,
          ``,
          `👑 *السائل (الجلاد):* ${tag1}`,
          `😈 *الضحية (المسؤول):* ${tag2}`,
          ``,
          `يلا يا ${tag1} اسأل ${tag2} أو اختار له زر من تحت 👇`,
        ].join('\n');

        return sendQuickReplies(sock, m.jid, {
          title: '🍾 دارت الزجاجة!',
          text: spinText,
          mentions: [p1, p2],
          buttons: [
            { label: '😳 حقيقة للضحية', id: '.td truth' },
            { label: '🔫 جرأة للضحية', id: '.td dare' },
            { label: '🍾 لفة جديدة', id: '.td spin' },
          ],
        });
      } catch (err) {
        return m.reply('⚠️ حصل خطأ أثناء سحب أعضاء الجروب، جرب تاني!');
      }
    }

    // 😳 حقيقة
    if (['truth', 'حقيقة', 'صراحة'].includes(rawArg)) {
      const q = pickItem(TRUTHS, last?.truth);
      games[m.jid] = { ...(games[m.jid] ?? {}), truth: q };
      db.set('td', games);

      return sendQuickReplies(sock, m.jid, {
        title: '😳 سؤال حقيقة وصراحة!',
        text: `*${q}*\n\nيلا جاوب بصراحة تامة ومن غير لف ودوران! 👇`,
        buttons: [
          { label: '😳 حقيقة تانية', id: '.td truth' },
          { label: '🔫 هات جرأة', id: '.td dare' },
          { label: '🍾 لِف الإزازة', id: '.td spin' },
        ],
      });
    }

    // 🔫 جرأة
    if (['dare', 'جرأة', 'تحدي'].includes(rawArg)) {
      const d = pickItem(DARES, last?.dare);
      games[m.jid] = { ...(games[m.jid] ?? {}), dare: d };
      db.set('td', games);

      return sendQuickReplies(sock, m.jid, {
        title: '🔫 تحدي وجرأة!',
        text: `*${d}*\n\nلو قدها نفذها وابعت الإثبات في الشات! 💪`,
        buttons: [
          { label: '🔫 جرأة تانية', id: '.td dare' },
          { label: '😳 هات حقيقة', id: '.td truth' },
          { label: '🍾 لِف الإزازة', id: '.td spin' },
        ],
      });
    }

    // 🎲 عشوائي
    if (['random', 'عشوائي', 'حظ'].includes(rawArg)) {
      const isTruth = Math.random() < 0.5;
      const text = isTruth ? pickItem(TRUTHS, last?.truth) : pickItem(DARES, last?.dare);
      games[m.jid] = { ...(games[m.jid] ?? {}), [isTruth ? 'truth' : 'dare']: text };
      db.set('td', games);

      return sendQuickReplies(sock, m.jid, {
        title: isTruth ? '😳 حظك جاب: حقيقة!' : '🔫 حظك جاب: جرأة!',
        text: `*${text}*\n\nنفذ بدون تردد! 🎯`,
        buttons: [
          { label: '🎲 جولة عشوائية', id: '.td random' },
          { label: '🍾 لِف الإزازة', id: '.td spin' },
        ],
      });
    }

    // القائمة الرئيسية للعبة
    return sendQuickReplies(sock, m.jid, {
      title: '🔥 لعبة حقيقة وجرأة (Truth or Dare)',
      text: 'اختار وضع اللعب المفضل ليك ولصحابك، أو لِف الإزازة في الجروب 👇',
      buttons: [
        { label: '😳 حقيقة', id: '.td truth' },
        { label: '🔫 جرأة', id: '.td dare' },
        { label: '🍾 لِف الإزازة', id: '.td spin' },
      ],
    });
  },
};
