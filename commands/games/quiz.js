const OPTION_PREFIXES = ['1️⃣ أ', '2️⃣ ب', '3️⃣ ج', '4️⃣ د'];
const DIGIT_MAP = { '1': 0, '2': 1, '3': 2, '4': 3, '١': 0, '٢': 1, '٣': 2, '٤': 3 };
const LETTER_MAP = { 'أ': 0, 'ا': 0, 'ب': 1, 'ج': 2, 'د': 3 };

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function state() {
  return db.get('quiz', {});
}

function nextQuestion(excludeIdx = -1) {
  let idx = Math.floor(Math.random() * QUESTIONS.length);
  if (excludeIdx >= 0 && QUESTIONS.length > 1 && idx === excludeIdx) {
    idx = (idx + 1) % QUESTIONS.length;
  }
  const order = shuffle([0, 1, 2, 3]);
  const question = QUESTIONS[idx];
  const allOpts = [question.a, ...question.wrong];
  const shuffledTexts = order.map((origIdx) => allOpts[origIdx]);

  return {
    q: idx,
    order,
    optionsText: shuffledTexts,
    at: Date.now(),
  };
}

function formatQuestionBody(st) {
  const question = QUESTIONS[st.q];
  const options = [question.a, ...question.wrong];
  const lines = [
    `🧠 *تحدي المعلومات والذكاء* 🏆`,
    ``,
    `❓ *${question.q}*`,
    ``,
  ];

  st.order.forEach((origIdx, shownPos) => {
    lines.push(`${OPTION_PREFIXES[shownPos]}) *${options[origIdx]}*`);
  });

  lines.push('');
  lines.push(`💡 *طريقة الإجابة السريعة:*`);
  lines.push(`جاوب برقم الخيار (*1* أو *2* أو *3* أو *4*) أو بالحرف (*أ*، *ب*، *ج*، *د*)`);
  lines.push(`أو اكتب نص الإجابة مباشرة! أول واحد يجاوب يكسب 💰`);

  return lines.join('\n');
}

function askButtons(st) {
  const question = QUESTIONS[st.q];
  const options = [question.a, ...question.wrong];
  return st.order.map((origIdx, shownPos) => ({
    label: `${shownPos + 1}. ${options[origIdx]}`,
    id: `.quiz ans-${st.q}-${shownPos}`,
  }));
}

