// 1) تطبيع النص: إزالة التشكيل + توحيد الحروف
export function normalizeArabic(input) {
  return String(input ?? '')
    .trim()
    .toLowerCase()
    .replace(/[ً-ْٰـ]/g, '')            // تشكيل وتطويل
    .replace(/[آأإاٱ]/g, 'ا')          // ألف بأشكالها
    .replace(/[ةه]/g, 'ه')             // تاء مربوطة وهواء
    .replace(/[ىئي]/g, 'ي')            // ياء بأشكالها
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/[ـ'’`".,!?؛:…]/g, '')   // رموز
    .replace(/\s+/g, ' ')
    .trim();
}

// 2) الأرقام العربية → لاتينية
const AR_DIGITS = {
  '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4',
  '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9',
  '۰': '0', '۱': '1', '۲': '2', '۳': '3', '۴': '4',
  '۵': '5', '۶': '6', '۷': '7', '۸': '8', '۹': '9',
};

export function toLatinDigits(text) {
  return String(text ?? '').replace(/[٠-٩۰-۹]/g, (d) => AR_DIGITS[d] ?? d);
}

// 3) الكلمات الرقمية → رقم (خمسه=5، عشرين=20، مية=100)
const WORD_NUMBERS = {
  'صفر': 0, 'واحد': 1, 'واحده': 1, 'اثنين': 2, 'اتنين': 2, 'تلات': 3, 'ثلاثه': 3,
  'اربع': 4, 'اربعه': 4, 'خمسه': 5, 'خمس': 5, 'سته': 6, 'ست': 6,
  'سبعه': 7, 'سبع': 7, 'ثمانه': 8, 'تمان': 8, 'تسعه': 9, 'تسع': 9,
  'عشر': 10, 'عشره': 10, 'عشرين': 20, 'ثلاثين': 30, 'اربعين': 40,
  'خمسين': 50, 'ستين': 60, 'سبعين': 70, 'تمانين': 80, 'تسعين': 90,
  'مائه': 100, 'ميه': 100, 'مية': 100, 'الف': 1000, 'الفين': 2000, 'تلاته_الاف': 3000,
};

export function parseArabicNumber(text) {
  const t = normalizeArabic(text);
  if (!t) return null;

  const direct = toLatinDigits(t);
  if (/^\d+$/.test(direct)) return Number(direct);

  for (const [word, num] of Object.entries(WORD_NUMBERS)) {
    if (t === word) return num;
    if (t.startsWith(word + ' ')) {
      const rest = parseArabicNumber(t.slice(word.length).trim());
      return rest !== null && rest > 0 ? num + rest : num;
    }
  }
  return null;
}

