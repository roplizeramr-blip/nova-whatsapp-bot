// 🔎 اقتراح الأمر من نية واضحة، لا من كلمة عابرة في جملة طويلة.
const HINT_INTENT = ['عايز','عاوزه','محتاج','ممكن','ازاي','كيف','فين','هات','ابعت','نزل','نزلي','حمل','حملي','شغل','ترجم','اقرا','اوصف','فكرني','ذكرني','اعرف','وريني','افتح','القائمه'].map(normalizeArabic);
export function hintFor(text) {
  const t = normalizeArabic(text);
  if (!t || !HINT_INTENT.some((intent) => t.includes(intent))) return null;
  let best = null;
  let bestLen = 0;
  for (const [word, cmd] of Object.entries(SMART_HINTS)) {
    const w = normalizeArabic(word);
    if (w && t.includes(w) && w.length > bestLen) {
      best = cmd;
      bestLen = w.length;
    }
  }
  return best;
}

// 6) البحث الذكي عن أمر
export function matchCommand(typed, availableNames) {
  const t = normalizeArabic(typed);
  if (!t) return null;

  if (availableNames.includes(t)) return t;
  for (const n of availableNames) {
    if (normalizeArabic(n) === t) return n;
  }

  let best = null;
  let bestDist = Infinity;
  for (const n of availableNames) {
    const d = levenshtein(t, normalizeArabic(n));
    if (d < bestDist) {
      bestDist = d;
      best = n;
    }
  }
  return bestDist <= 2 ? best : null;
}

function levenshtein(a, b) {
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 0; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++)
    for (let j = 1; j <= b.length; j++)
      d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return d[a.length][b.length];
}
